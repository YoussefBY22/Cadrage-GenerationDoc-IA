"""Interface du dépôt de données (06 §4.1) : seule porte d'accès au stockage."""

from collections.abc import Iterator
from typing import Literal, Protocol

from ..domain.coeur import ExistingProject, Priority
from ..domain.context import ContextData, ContextSheet
from ..domain.decisions import Decision
from ..domain.documents import Chunk, ParsedDocument
from ..domain.generation import DeliverableContent, Finding
from ..domain.ids import DeliverableType, Lang
from ..domain.retrieval import Passage
from ..domain.verification import VerificationReport
from ..domain.workflow import Role, State


class DuplicateDocumentError(Exception):
    """Un document de même empreinte sha256 existe déjà dans le dossier."""


class Repository(Protocol):
    # dossiers et utilisateurs
    def create_dossier(self, name: str, client_name: str, language: Lang, owner_id: str) -> str: ...
    def get_dossier(self, dossier_id: str) -> dict | None: ...
    def list_dossiers(self, user_id: str) -> list[dict]: ...
    def add_member(self, dossier_id: str, user_id: str, role: Role) -> None: ...
    def member_role(self, dossier_id: str, user_id: str) -> Role | None: ...
    def create_user(self, email: str, display_name: str, password_hash: str, role: Role) -> str: ...
    def get_user_by_email(self, email: str) -> dict | None: ...
    # documents et passages
    def add_document(self, dossier_id: str, parsed: ParsedDocument, stored_path: str,
                     role: str = "other") -> str: ...
    def set_document_role(self, document_id: str, role: str) -> None: ...
    def document_roles(self, dossier_id: str) -> dict[str, str]: ...
    def find_document_by_sha(self, dossier_id: str, sha256: str) -> str | None: ...
    def add_chunks(self, chunks: list[Chunk], embeddings: list[list[float]],
                   model: str) -> None: ...
    def get_chunks(self, dossier_id: str, chunk_ids: list[str]) -> dict[str, Chunk]: ...
    def iter_chunks(self, dossier_id: str,
                    document_ids: list[str] | None = None) -> Iterator[Chunk]: ...
    def vector_search(self, dossier_id: str, query: list[float], k: int,
                      document_ids: list[str] | None = None) -> list[tuple[str, float]]: ...
    # constats, livrables, versions, validation
    def save_findings(self, dossier_id: str, findings: list[Finding]) -> None: ...
    def list_findings(self, dossier_id: str, validated_only: bool = False) -> list[Finding]: ...
    def create_deliverable(self, dossier_id: str, type: DeliverableType, template_id: str,
                           author_id: str) -> str: ...
    def add_version(self, deliverable_id: str, content: DeliverableContent, author_id: str,
                    origin: Literal["generated", "edited", "restored"]) -> int: ...
    def get_version(self, deliverable_id: str,
                    version: int | None = None) -> tuple[int, DeliverableContent]: ...
    def set_state(self, deliverable_id: str, state: State, user_id: str,
                  reason: str | None) -> None: ...
    # priorités institutionnelles et projets existants
    def create_priority(self, dossier_id: str, *, title: str, description: str, rank: int,
                        status: str, source_ids: list[str], author_id: str | None) -> Priority: ...
    def get_priority(self, priority_id: str) -> Priority | None: ...
    def list_priorities(self, dossier_id: str, status: str | None = None) -> list[Priority]: ...
    def update_priority(self, priority_id: str, **values) -> Priority | None: ...
    def delete_priority(self, priority_id: str) -> None: ...
    def create_project(self, dossier_id: str, *, title: str, state: str,
                       duration_weeks: int | None, depends_on: list[str], source_ids: list[str],
                       author_id: str | None) -> ExistingProject: ...
    def get_project(self, project_id: str) -> ExistingProject | None: ...
    def list_projects(self, dossier_id: str) -> list[ExistingProject]: ...
    def update_project(self, project_id: str, **values) -> ExistingProject | None: ...
    def delete_project(self, project_id: str) -> None: ...
    # fiche de contexte (FR-25)
    def get_context(self, dossier_id: str) -> ContextSheet | None: ...
    def save_context(self, dossier_id: str, data: ContextData, *, user_id: str | None,
                     confirmed: bool) -> ContextSheet: ...
    # décisions humaines (FR-23) : seules les confirmées comptent
    def create_decision(self, dossier_id: str, *, category: str, text: str, status: str,
                        author_id: str | None) -> Decision: ...
    def get_decision(self, decision_id: str) -> Decision | None: ...
    def list_decisions(self, dossier_id: str, status: str | None = None) -> list[Decision]: ...
    def update_decision(self, decision_id: str, **values) -> Decision | None: ...
    def delete_decision(self, decision_id: str) -> None: ...
    # traces (alimentent l'entrepôt)
    def record_run(self, run: dict) -> str: ...
    def record_retrieval(self, run_id: str, passages: list[Passage]) -> None: ...
    def record_verification(self, run_id: str, report: VerificationReport) -> None: ...
    def audit(self, user_id: str | None, action: str, object_type: str, object_id: str,
              details: dict) -> None: ...
    def record_alert(self, chunk_id: str, codes: list[str]) -> None: ...
